#!/usr/bin/env node
// Generates app/lib/core/design/stize_tokens.dart from stize.tokens.json.
//
// The JSON is a copy of the Stiže design system's tokens (the master lives in
// the owner's design-system artifact). To update: replace stize.tokens.json
// whole, then run `node design/tokens/gen-tokens.mjs` from the repo root.
// No dependencies, no network. Unknown value formats fail loudly.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const src = join(here, "stize.tokens.json");
const out = join(root, "app", "lib", "core", "design", "stize_tokens.dart");

const tokens = JSON.parse(readFileSync(src, "utf8"));

const camel = (name) =>
  name.replace(/[-.]([a-z0-9])/gi, (_, c) => c.toUpperCase());

function hex2(n) {
  return n.toString(16).padStart(2, "0").toUpperCase();
}

// '#RRGGBB' | '#RRGGBBAA' | 'rgba(r,g,b,a)' | 'rgb(r,g,b)' -> 'Color(0xAARRGGBB)'
function color(v, name) {
  v = String(v).trim();
  let m = v.match(/^#([0-9a-f]{6})([0-9a-f]{2})?$/i);
  if (m) {
    const a = m[2] ? m[2].toUpperCase() : "FF";
    return `Color(0x${a}${m[1].toUpperCase()})`;
  }
  m = v.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/i);
  if (m) {
    const a = m[4] === undefined ? 1 : Number(m[4]);
    return `Color(0x${hex2(Math.round(a * 255))}${hex2(+m[1])}${hex2(+m[2])}${hex2(+m[3])})`;
  }
  throw new Error(`Unsupported colour value for ${name}: ${v}`);
}

function px(v, name) {
  const m = String(v).trim().match(/^(-?[\d.]+)(px)?$/);
  if (!m) throw new Error(`Unsupported length for ${name}: ${v}`);
  return Number(m[1]);
}

const num = (n) => (Number.isInteger(n) ? `${n}.0` : `${n}`);

// '0 -12px 32px rgba(0,0,0,0.45), 0 4px 16px rgba(...)' -> BoxShadow list
function shadows(v, name) {
  const parts = String(v).match(/-?[\d.]+(?:px)?\s+-?[\d.]+(?:px)?\s+-?[\d.]+(?:px)?(?:\s+-?[\d.]+(?:px)?)?\s+(?:rgba?\([^)]*\)|#[0-9a-f]{6,8})/gi);
  if (!parts) throw new Error(`Unsupported shadow for ${name}: ${v}`);
  return parts.map((p) => {
    const c = p.match(/(rgba?\([^)]*\)|#[0-9a-f]{6,8})$/i)[1];
    const n = p.replace(c, "").trim().split(/\s+/).map((x) => px(x, name));
    const [x, y, blur, spread = 0] = n;
    return `BoxShadow(offset: Offset(${num(x)}, ${num(y)}), blurRadius: ${num(blur)}, spreadRadius: ${num(spread)}, color: ${color(c, name)})`;
  });
}

// ---- colours
const themes = tokens.color.themes.map((t) => t.id);
const first = themes[0];
const colorTokens = tokens.color.tokens.map((t) => {
  const val = typeof t.value === "string" ? { [first]: t.value } : t.value;
  const per = {};
  for (const th of themes) per[th] = color(val[th] ?? val[first], t.name);
  return { name: t.name, field: camel(t.name), usage: t.usage ?? "", per };
});
const seen = new Set();
for (const c of colorTokens) {
  if (seen.has(c.field)) throw new Error(`Duplicate colour token ${c.name}`);
  seen.add(c.field);
}

const L = [];
L.push("// GENERATED by design/tokens/gen-tokens.mjs from design/tokens/stize.tokens.json.");
L.push("// Do not edit by hand: change the JSON (a copy of the Stiže design system) and");
L.push("// rerun `node design/tokens/gen-tokens.mjs` from the repo root.");
L.push("// (Named without .g.dart on purpose: that suffix is gitignored in this repo.)");
L.push("// ignore_for_file: lines_longer_than_80_chars");
L.push("");
L.push("import 'package:flutter/material.dart';");
L.push("");
L.push("/// Theme-aware colours of the Stiže design system. Read with");
L.push("/// `StizeColors.of(context)`.");
L.push("@immutable");
L.push("class StizeColors extends ThemeExtension<StizeColors> {");
L.push("  const StizeColors({");
for (const c of colorTokens) L.push(`    required this.${c.field},`);
L.push("  });");
L.push("");
for (const c of colorTokens) {
  L.push(`  /// \`${c.name}\`: ${c.usage.replace(/\s+/g, " ").replace(/\*\//g, "")}`);
  L.push(`  final Color ${c.field};`);
}
L.push("");
for (const th of themes) {
  L.push(`  static const ${camel(th)} = StizeColors(`);
  for (const c of colorTokens) L.push(`    ${c.field}: ${c.per[th]},`);
  L.push("  );");
  L.push("");
}
L.push("  /// The colours of the current theme; dark when the extension is missing.");
L.push("  static StizeColors of(BuildContext context) =>");
L.push("      Theme.of(context).extension<StizeColors>() ?? dark;");
L.push("");
L.push("  /// Token name -> colour, for tests and debugging.");
L.push("  Map<String, Color> toMap() => {");
for (const c of colorTokens) L.push(`        '${c.name}': ${c.field},`);
L.push("      };");
L.push("");
L.push("  @override");
L.push("  StizeColors copyWith({");
for (const c of colorTokens) L.push(`    Color? ${c.field},`);
L.push("  }) =>");
L.push("      StizeColors(");
for (const c of colorTokens) L.push(`        ${c.field}: ${c.field} ?? this.${c.field},`);
L.push("      );");
L.push("");
L.push("  @override");
L.push("  StizeColors lerp(ThemeExtension<StizeColors>? other, double t) {");
L.push("    if (other is! StizeColors) return this;");
L.push("    return StizeColors(");
for (const c of colorTokens) L.push(`      ${c.field}: Color.lerp(${c.field}, other.${c.field}, t)!,`);
L.push("    );");
L.push("  }");
L.push("}");
L.push("");

// ---- plain number families
function family(cls, fam, doc) {
  if (!tokens[fam]) return;
  L.push(`/// ${doc}`);
  L.push(`abstract final class ${cls} {`);
  for (const t of tokens[fam].tokens) {
    L.push(`  /// \`${t.name}\`: ${(t.usage ?? "").replace(/\s+/g, " ")}`);
    L.push(`  static const double ${camel(t.name)} = ${num(px(t.value, t.name))};`);
  }
  L.push("}");
  L.push("");
}
family("StizeSpace", "spacing", "Spacing on the 4px grid.");
family("StizeRadius", "radius", "Corner radii.");
family("StizeSize", "size", "Component sizes.");

if (tokens.shadow) {
  L.push("/// Shadows.");
  L.push("abstract final class StizeShadow {");
  for (const t of tokens.shadow.tokens) {
    L.push(`  /// \`${t.name}\`: ${(t.usage ?? "").replace(/\s+/g, " ")}`);
    L.push(`  static const List<BoxShadow> ${camel(t.name)} = [`);
    for (const s of shadows(t.value, t.name)) L.push(`    ${s},`);
    L.push("  ];");
  }
  L.push("}");
  L.push("");
}

// ---- type
const famMap = { sans: "UncutSans", mono: "GeistMono" };
L.push("/// Font families as declared in app/pubspec.yaml.");
L.push("abstract final class StizeFonts {");
L.push(`  static const String sans = '${famMap.sans}';`);
L.push(`  static const String mono = '${famMap.mono}';`);
L.push("}");
L.push("");
L.push("/// The type scale. Colour is left to the caller (from StizeColors).");
L.push("abstract final class StizeType {");
for (const g of tokens.type.groups) {
  const fam = famMap[g.family];
  if (!fam) throw new Error(`Unknown family ${g.family}`);
  for (const s of g.styles) {
    const size = px(s.fontSize, s.name);
    const lh = px(s.lineHeight, s.name);
    const w = Number(s.fontWeight);
    const em = String(s.letterSpacing ?? "0").trim();
    const ls = em.endsWith("em") ? Number(em.slice(0, -2)) * size : px(em || 0, s.name);
    L.push(`  /// \`${s.name}\` ${size}/${lh} w${w}: ${(s.usage ?? "").replace(/\s+/g, " ")}`);
    L.push(`  static const TextStyle ${camel(s.name)} = TextStyle(`);
    L.push(`    fontFamily: StizeFonts.${g.family},`);
    L.push(`    fontSize: ${num(size)},`);
    L.push(`    height: ${lh / size},`);
    L.push(`    fontWeight: FontWeight.w${w},`);
    L.push(`    letterSpacing: ${num(Math.round(ls * 1000) / 1000)},`);
    L.push("  );");
  }
}
L.push("}");
L.push("");

writeFileSync(out, L.join("\n"));
console.log(`wrote ${out} (${colorTokens.length} colours)`);
